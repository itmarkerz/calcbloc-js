#!/usr/bin/env node
/**
 * Generates one module per bundled country (dist/countries/<country>.{js,cjs,d.ts,d.cts}) from data/manifest.json,
 * served as calcbloc/tables/<country>. Each module imports its JSON files statically, so a bundler includes only
 * the countries an app imports. Runs after tsup (`npm run build`).
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "dist", "countries");
const manifest = JSON.parse(readFileSync(join(ROOT, "data", "manifest.json"), "utf8"));

const ID = /^[a-z0-9-]+$/;
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const header = (c) => `// calcbloc/tables/${c.country}: ${c.name} tax tables (${c.years.join(", ")}). Generated by scripts/build-countries.mjs.\n// Data: CC BY 4.0. Credit "Data by CalcBloc (calcbloc.com/data)" with a link to https://calcbloc.com/data.\n`;

for (const c of manifest.countries) {
  if (!ID.test(c.country)) throw new Error(`Unexpected country id ${c.country}`);
  const files = c.files.filter((f) => /^[a-z0-9-]+\/[A-Za-z0-9-]+(\/[a-z0-9-]+)?\.json$/.test(f));
  if (files.length !== c.files.length) throw new Error(`Unexpected file name in ${c.country}: ${c.files.join(", ")}`);
  const entry = JSON.stringify(c);

  const esm = [
    header(c),
    `import { defineCountry } from "../country.js";`,
    ...files.map((f, i) => `import f${i} from "../../data/${f}" with { type: "json" };`),
    ``,
    `export const tables = defineCountry(${entry}, {`,
    ...files.map((f, i) => `  ${JSON.stringify(f)}: f${i},`),
    `});`,
    `export default tables;`,
    ``,
  ].join("\n");

  const cjs = [
    header(c),
    `"use strict";`,
    `Object.defineProperty(exports, "__esModule", { value: true });`,
    `const { defineCountry } = require("../country.cjs");`,
    ``,
    `const tables = defineCountry(${entry}, {`,
    ...files.map((f) => `  ${JSON.stringify(f)}: require(${JSON.stringify(`../../data/${f}`)}),`),
    `});`,
    `exports.tables = tables;`,
    `exports.default = tables;`,
    ``,
  ].join("\n");

  const dts = (ext) => [`import type { CountryTables } from "../country.${ext}";`, `/** ${c.name} tax tables: ${c.years.join(", ")}${c.regions.length ? `, ${c.regions.length} regions` : ""}. */`, `export declare const tables: CountryTables;`, `export default tables;`, ``].join("\n");

  writeFileSync(join(OUT, `${c.country}.js`), esm);
  writeFileSync(join(OUT, `${c.country}.cjs`), cjs);
  writeFileSync(join(OUT, `${c.country}.d.ts`), dts("js"));
  writeFileSync(join(OUT, `${c.country}.d.cts`), dts("cjs"));
}

console.log(`Generated calcbloc/tables/<country> modules for ${manifest.countries.length} countries in dist/countries/`);
